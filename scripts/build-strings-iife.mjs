/* GENERATOR: src/demo/strings.iife.js — classic-script strings global for
 * file:// demos (mirrors icons.iife.js). Embeds en-us + every locale so demos
 * can switch language. Run after regenerating the dictionaries:
 *   node scripts/extract-strings.mjs && node scripts/build-locales.mjs && node scripts/build-strings-iife.mjs
 *
 *   window.SpixiStrings.enUS         — canonical en-us dictionary
 *   window.SpixiStrings.locales      — { 'de-de': {...}, ... } starter locales
 *   window.SpixiStrings.pseudo()     — marker locale (any plain English = a hardcoded string)
 *   window.SpixiStrings.get(code)    — 'en-us' | '<locale>' | 'pseudo' -> a strings object
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const LOCALES = ['de-de', 'es-co', 'fr-fr', 'sr-sp', 'sl-si', 'ru-ru', 'pt-br'];
const enUS = JSON.parse(readFileSync(join(root, 'src/strings/en-us.json'), 'utf8'));
const locales = {};
for (const c of LOCALES) {
  const p = join(root, 'src/strings', c + '.json');
  if (existsSync(p)) locales[c] = JSON.parse(readFileSync(p, 'utf8'));
}
const out = `/* GENERATED by scripts/build-strings-iife.mjs — DO NOT EDIT.
 * en-us (${Object.keys(enUS).length} keys) + ${Object.keys(locales).length} starter locales + pseudo marker locale.
 */
(function () {
  var enUS = ${JSON.stringify(enUS, null, 0)};
  var locales = ${JSON.stringify(locales, null, 0)};
  function pseudo() {
    return new Proxy({}, { get: function (_t, k) { return typeof k === 'string' ? '\\u27E6' + k + '\\u27E7' : undefined; } });
  }
  window.SpixiStrings = {
    enUS: enUS,
    locales: locales,
    pseudo: pseudo,
    get: function (code) {
      if (code === 'pseudo') return pseudo();
      if (code && code !== 'en-us' && locales[code]) return locales[code];
      return enUS;
    }
  };
})();
`;
writeFileSync(join(root, 'src/demo/strings.iife.js'), out);
console.log('wrote src/demo/strings.iife.js (en-us + ' + Object.keys(locales).length + ' locales + pseudo)');
