/* GENERATOR: src/demo/strings.iife.js — classic-script strings global for
 * file:// demos (mirrors icons.iife.js). Embeds en-us + every locale so demos
 * can switch language. Run after regenerating the dictionaries:
 *   node scripts/extract-strings.mjs && node scripts/build-locales.mjs && node scripts/build-strings-iife.mjs
 *
 *   window.SpixiStrings.enUS         — canonical en-us dictionary
 *   window.SpixiStrings.locales      — { 'de-de': {...}, ... } starter locales
 *   window.SpixiStrings.pseudo()     — marker locale (any plain English = a hardcoded string)
 *   window.SpixiStrings.get(code)    — 'en-us' | '<locale>' | 'pseudo' -> a strings object
 *                                      (SIDE EFFECT: also sets <html lang> — see setDocLang below)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const LOCALES = ['de-de', 'es-co', 'fr-fr', 'sr-sp', 'sl-si', 'ru-ru', 'pt-br',
  'it-it', 'id-id', 'lt-lt', 'cn-cn', 'ja-jp'];   // N4 (#379)
const enUS = JSON.parse(readFileSync(join(root, 'src/strings/en-us.json'), 'utf8'));
const locales = {};
for (const c of LOCALES) {
  const p = join(root, 'src/strings', c + '.json');
  if (existsSync(p)) locales[c] = JSON.parse(readFileSync(p, 'utf8'));
}
const out = `/* GENERATED by scripts/build-strings-iife.mjs — DO NOT EDIT.
 * en-us (${Object.keys(enUS).length} keys) + ${Object.keys(locales).length} starter locales + pseudo marker locale.
 */
(function () {
  var enUS = ${JSON.stringify(enUS, null, 0)};
  var locales = ${JSON.stringify(locales, null, 0)};
  function pseudo() {
    return new Proxy({}, { get: function (_t, k) { return typeof k === 'string' ? '\\u27E6' + k + '\\u27E7' : undefined; } });
  }
  /* THE DOCUMENT LOCALE — not just the dictionary (Q3, #269).
   * timestamp.js docLocale() reads document.documentElement.lang, and that is THE
   * locale for every Intl / toLocale* call in the components: chat-list timestamps,
   * date separators, wallet tx dates, bubble times. Every shell ships a static
   * <html lang="en"> and nothing ever reassigned it, so a de-de / fr-fr / ru-ru UI
   * still rendered English weekdays + English month abbreviations + a 12-hour clock.
   * It is set HERE because get() is the ONE place all 22 shells and every demo boot
   * through (window.SL = window.SpixiStrings.get(code)) — one fix, no per-shell
   * duplication. get()'s RETURN VALUE is unchanged; this is a pure side effect.
   * Skipped for: 'pseudo' (not a real locale), the un-substituted '*SL{language-code}'
   * marker (plain-browser preview / no C# substitution), and any code we have no
   * dictionary for — a locale whose text falls back to English must keep lang="en",
   * or a screen reader would voice English copy with e.g. Italian phonetics (the
   * hidden dictionary-less locales of #257 can still be persisted by App.xaml.cs). */
  function setDocLang(code) {
    if (typeof document === 'undefined' || !code) return;
    if (!/^[a-z]{2}(-[a-z]{2,4})?$/i.test(code)) return;          // 'pseudo', '*SL{…}', junk
    if (code !== 'en-us' && !locales[code]) return;               // no dictionary → stay English
    /* N4 (#379): cn-cn is the SpixiLocalization file code, NOT a Chinese BCP-47
     * tag ("cn" ≠ "zh"). The dictionary key stays cn-cn end-to-end; only the
     * DOCUMENT locale maps to zh-cn, so Intl dates and screen readers get real
     * Chinese instead of root-locale fallback under a junk tag. */
    var docCode = code === 'cn-cn' ? 'zh-cn' : code;
    try {
      Intl.getCanonicalLocales(docCode);                          // throws on a bad tag
      document.documentElement.lang = docCode;
    } catch (e) { /* never throw at boot — keep the markup default */ }
  }
  window.SpixiStrings = {
    enUS: enUS,
    locales: locales,
    pseudo: pseudo,
    setDocLang: setDocLang,
    get: function (code) {
      setDocLang(code);                                           // side effect: <html lang>
      if (code === 'pseudo') return pseudo();
      if (code && code !== 'en-us' && locales[code]) return locales[code];
      return enUS;
    }
  };
})();
`;
writeFileSync(join(root, 'src/demo/strings.iife.js'), out);
console.log('wrote src/demo/strings.iife.js (en-us + ' + Object.keys(locales).length + ' locales + pseudo)');
